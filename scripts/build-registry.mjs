#!/usr/bin/env node
/**
 * Builds data/courses.js from the <meta name="course:*"> tags in each
 * courses/<slug>/index.html.
 *
 *   node scripts/build-registry.mjs            rewrite the registry
 *   node scripts/build-registry.mjs --check    exit 1 if it's stale (for CI)
 *
 * The course files are the single source of truth. Nothing here needs editing
 * when you add a course.
 */

import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const COURSES_DIR = join(ROOT, "courses");
const OUT = join(ROOT, "data", "courses.js");

const CHECK = process.argv.includes("--check");

const DEFAULTS = {
  description: "",
  level: "",
  duration: "",
  type: "course",
  accent: "#6FD4E0",
  icon: "📘",
  status: "live",
  order: 100
};

/* ---------- parsing ---------- */

const ENTITIES = {
  "&amp;": "&",
  "&lt;": "<",
  "&gt;": ">",
  "&quot;": '"',
  "&#39;": "'",
  "&apos;": "'",
  "&nbsp;": " "
};

function decode(s) {
  return s
    .replace(/&(?:amp|lt|gt|quot|#39|apos|nbsp);/g, (m) => ENTITIES[m])
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)));
}

/** Pull every <meta name="course:X" content="Y"> out of a document. */
function courseMeta(html) {
  const out = {};
  // Only look at the <head> — avoids picking up meta tags a course might
  // render into its own body content as example markup.
  const head = html.slice(0, (html.search(/<\/head>/i) + 1) || html.length);

  for (const tag of head.match(/<meta\b[^>]*>/gi) || []) {
    const name = tag.match(/\bname\s*=\s*["']course:([a-z]+)["']/i);
    if (!name) continue;
    const content = tag.match(/\bcontent\s*=\s*"([^"]*)"/i) || tag.match(/\bcontent\s*=\s*'([^']*)'/i);
    if (content) out[name[1].toLowerCase()] = decode(content[1]).trim();
  }
  return out;
}

/* ---------- collection ---------- */

const problems = [];

function readCourse(slug) {
  const file = join(COURSES_DIR, slug, "index.html");
  if (!existsSync(file)) {
    problems.push(`${slug}/ has no index.html — skipped`);
    return null;
  }

  const meta = courseMeta(readFileSync(file, "utf8"));

  if (!meta.title) {
    problems.push(`${slug}/index.html has no <meta name="course:title"> — skipped`);
    return null;
  }
  for (const field of ["description", "tags"]) {
    if (!meta[field]) problems.push(`${slug}: missing course:${field}`);
  }

  const tags = (meta.tags || "")
    .split(",")
    .map((t) => t.trim().toLowerCase())
    .filter(Boolean);

  const order = Number.parseInt(meta.order, 10);

  return {
    slug,
    href: `courses/${slug}/`,
    title: meta.title,
    description: meta.description ?? DEFAULTS.description,
    tags,
    level: meta.level ?? DEFAULTS.level,
    duration: meta.duration ?? DEFAULTS.duration,
    type: meta.type || DEFAULTS.type,
    accent: meta.accent || DEFAULTS.accent,
    icon: meta.icon || DEFAULTS.icon,
    status: meta.status || DEFAULTS.status,
    order: Number.isFinite(order) ? order : DEFAULTS.order
  };
}

const courses = readdirSync(COURSES_DIR, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => readCourse(e.name))
  .filter(Boolean)
  .sort((a, b) => a.order - b.order || a.title.localeCompare(b.title));

/* ---------- emit ---------- */

const q = (s) => JSON.stringify(String(s));

function render(list) {
  const entries = list.map((c) => {
    const tags = c.tags.length ? c.tags.map(q).join(", ") : "";
    return [
      "  {",
      `    slug: ${q(c.slug)},`,
      `    href: ${q(c.href)},`,
      `    title: ${q(c.title)},`,
      `    description: ${q(c.description)},`,
      `    tags: [${tags}],`,
      `    level: ${q(c.level)},`,
      `    duration: ${q(c.duration)},`,
      `    type: ${q(c.type)},`,
      `    accent: ${q(c.accent)},`,
      `    icon: ${q(c.icon)},`,
      `    status: ${q(c.status)},`,
      `    order: ${c.order}`,
      "  }"
    ].join("\n");
  });

  return [
    "/**",
    " * Course registry.",
    " *",
    " * GENERATED by scripts/build-registry.mjs from the <meta name=\"course:*\"> tags",
    " * in each courses/<slug>/index.html. Do not edit by hand — rerun",
    " * `npm run build:registry` instead, or just push and let CI rebuild it.",
    " */",
    "window.COURSES = [",
    entries.join(",\n"),
    "];",
    ""
  ].join("\n");
}

const next = render(courses);
const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";

for (const p of problems) console.warn(`  warning: ${p}`);

if (CHECK) {
  if (next === current) {
    console.log(`Registry is up to date (${courses.length} courses).`);
    process.exit(0);
  }
  console.error(
    "\nRegistry is stale — data/courses.js does not match the course files.\n" +
      "Run `npm run build:registry` and commit the result.\n"
  );
  process.exit(1);
}

if (next === current) {
  console.log(`Registry unchanged (${courses.length} courses).`);
} else {
  writeFileSync(OUT, next, "utf8");
  console.log(`Wrote data/courses.js (${courses.length} courses).`);
}

for (const c of courses) {
  console.log(`  ${c.status === "live" ? "·" : "×"} ${c.slug.padEnd(24)} ${c.tags[0] || "-"}`);
}
